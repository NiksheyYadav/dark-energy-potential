# Pre-arXiv classics, checked against Crossref (title, author, journal, volume, page) on 2026-11-18.
MANUAL = r"""
@article{Stelle1977, author={Stelle, K. S.}, title={Renormalization of higher-derivative quantum gravity},
  journal={Phys. Rev. D}, volume={16}, pages={953}, year={1977}, doi={10.1103/PhysRevD.16.953}}
@article{Starobinsky1980, author={Starobinsky, A. A.}, title={A new type of isotropic cosmological models without singularity},
  journal={Phys. Lett. B}, volume={91}, pages={99}, year={1980}, doi={10.1016/0370-2693(80)90670-X}}
@article{Simon1990, author={Simon, J. Z.}, title={Higher-derivative {L}agrangians, nonlocality, problems, and solutions},
  journal={Phys. Rev. D}, volume={41}, pages={3720}, year={1990}, doi={10.1103/PhysRevD.41.3720}}
"""

NS = {"a": "http://www.w3.org/2005/Atom", "x": "http://arxiv.org/schemas/atom"}


GREEK = "alpha beta gamma delta epsilon zeta eta theta iota kappa lambda mu nu xi omicron pi rho varsigma sigma tau upsilon phi chi psi omega".split()


def esc(s):
    s = " ".join(s.split()).replace("&", r"\&").replace("%", r"\%").replace("#", r"\#")
    for i, name in enumerate(GREEK):              # Unicode Greek -> LaTeX (pdfLaTeX rejects it in math)
        s = s.replace(chr(0x3B1 + i), "o" if name == "omicron" else r"\ensuremath{\%s}" % name)
    return s


out, fail = [], []
for i in range(0, len(IDS), 40):
    chunk = IDS[i:i + 40]
    url = "https://export.arxiv.org/api/query?max_results=100&id_list=" + ",".join(chunk)
    root = ET.fromstring(urllib.request.urlopen(url, timeout=60).read())
    got = {}
    for e in root.findall("a:entry", NS):
        raw = e.find("a:id", NS).text.split("/abs/")[-1]
        aid = raw.rsplit("v", 1)[0] if raw[-1].isdigit() and "v" in raw else raw
        got[aid] = e
    for aid in chunk:
        e = got.get(aid)
        if e is None or e.find("a:title", NS) is None:
            fail.append(aid); continue
        auth = " and ".join(esc(a.find("a:name", NS).text) for a in e.findall("a:author", NS))
        if auth.count(" and ") > 14:
            auth = " and ".join(auth.split(" and ")[:10]) + " and others"
        f = dict(author=auth, title="{" + esc(e.find("a:title", NS).text) + "}",
                 year=e.find("a:published", NS).text[:4], eprint=aid, archivePrefix="arXiv",
                 primaryClass=e.find("x:primary_category", NS).get("term"))
        jr, doi = e.find("x:journal_ref", NS), e.find("x:doi", NS)
        if jr is not None: f["journal"] = esc(jr.text)
        if doi is not None: f["doi"] = doi.text
        body = ",\n  ".join("%s = {%s}" % kv for kv in f.items())
        kind = "article" if "journal" in f else "misc"   # unpublished preprints: no empty-journal warning
        out.append("@%s{%s,\n  %s\n}" % (kind, aid.replace("/", "_"), body))
    time.sleep(3)

with open(os.path.join(os.path.dirname(__file__), "refs.bib"), "w", encoding="utf-8") as fh:
    fh.write("% generated by make_bib.py from the arXiv API\n" + "\n\n".join(out) + "\n" + MANUAL)
print("entries:", len(out), "failed:", fail)
