"""
Coverage of the three uncertainty estimates on the 50 mocks (REPORT.md Sec. 4.9).

For each mock and quantity, pit = fraction of posterior/ensemble samples below the truth.
A central credible interval of level a contains the truth iff |pit - 0.5| <= a/2, so
  empirical coverage(a) = mean over mocks of [ |pit - 0.5| <= a/2 ].
Calibrated uncertainties give coverage(a) = a; binomial error bars for 50 mocks are shown.

  python src/coverage_analysis.py   ->  figures/coverage.png, results/coverage_summary.md
"""
import os, sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from data import ROOT
from coverage_common import truth_values, QUANT, SUFFIX, TRUTH_ID

sys.stdout.reconfigure(encoding="utf-8")
R = os.path.join(ROOT, "results")
METHODS = [("coverage_nn", "neural bootstrap ensemble", "C3"),
           ("coverage_mcmc_poly2", "emcee, slope + curvature", "C0"),
           ("coverage_mcmc_exp", "emcee, exponential (reference)", "C2")]
LAB = dict(H0="H0", Om="Ω_m", w0="w0", dphi="|Δφ|", vratio="V0/Vi")
tv = truth_values()
levels = np.linspace(0.02, 0.98, 49)
res = {}
for key, name, col in METHODS:
    f = os.path.join(R, key + SUFFIX + ".npz")
    if os.path.exists(f):
        res[key] = np.load(f, allow_pickle=True)

lines = ["# Coverage study (auto-generated by src/coverage_analysis.py)\n",
         f"Truth {TRUTH_ID}: " + ", ".join("%s = %.4f" % (LAB[k], tv[k]) for k in QUANT) + "\n"]
fig, ax = plt.subplots(1, len(QUANT), figsize=(3.3 * len(QUANT), 3.6), sharey=True)
for key, name, col in METHODS:
    if key not in res:
        continue
    d = res[key]
    pit, pct = d["pit"], d["pct"]                         # (n_mock, n_quant), (n_mock, n_quant, 5)
    n = len(pit)
    extra = ""
    if "tau" in d.files:
        extra = " | 50τ rule: steps/τ median %.0f (min %.0f); total runtime %.0f s" % (
            np.nanmedian(int(d["steps"]) / d["tau"]), np.nanmin(int(d["steps"]) / d["tau"]), float(d["total_runtime"]))
    elif "runtime" in d.files:
        extra = " | runtime %.0f s for %d networks" % (float(d["runtime"]), n * int(d["members"]))
    lines.append(f"\n## {name} ({n} mocks){extra}\n")
    lines.append("| quantity | truth | mean of medians | bias / mean σ | mean σ (68% half-width) | scatter of medians | coverage 68% | coverage 95% |")
    lines.append("|---|---|---|---|---|---|---|---|")
    for i, q in enumerate(QUANT):
        dev = np.abs(pit[:, i] - 0.5)
        c68, c95 = np.mean(dev <= 0.34135), np.mean(dev <= 0.4775)
        med = pct[:, i, 2]; sig = 0.5 * (pct[:, i, 3] - pct[:, i, 1])
        lines.append("| %s | %.4f | %.4f | %+.2f | %.4f | %.4f | %.0f%% | %.0f%% |" % (
            LAB[q], tv[q], med.mean(), (med.mean() - tv[q]) / sig.mean(), sig.mean(), med.std(ddof=1), 100 * c68, 100 * c95))
        cov = np.array([np.mean(dev <= a / 2) for a in levels])
        ax[i].plot(levels, cov, color=col, lw=1.6, label=name)
nm = len(next(iter(res.values()))["pit"])
for i, q in enumerate(QUANT):
    se = np.sqrt(levels * (1 - levels) / nm)
    ax[i].fill_between(levels, levels - 2 * se, levels + 2 * se, color="gray", alpha=0.2, label=f"±2σ binomial ({nm} mocks)" if i == 0 else None)
    ax[i].plot([0, 1], [0, 1], "k--", lw=0.8)
    ax[i].set_title(LAB[q]); ax[i].set_xlabel("nominal credible level")
ax[0].set_ylabel("fraction of mocks containing the truth")
ax[0].legend(fontsize=6.5, loc="upper left")
fig.tight_layout(); fig.savefig(os.path.join(ROOT, "figures", f"coverage{SUFFIX}.png"), dpi=130)
lines.append(f"\nCoverage ±1σ binomial for {nm} mocks: 68% ± {100 * np.sqrt(0.68 * 0.32 / nm):.1f}%, 95% ± {100 * np.sqrt(0.95 * 0.05 / nm):.1f}%. The neural ensemble has 23 bootstrap members per sky, so its 95% interval is the full range of 22–23 members and its coverage at that level is only roughly defined.")
with open(os.path.join(R, f"coverage_summary{SUFFIX}.md"), "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines) + "\n")
print("\n".join(lines))
